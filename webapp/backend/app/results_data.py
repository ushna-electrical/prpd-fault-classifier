"""Loads thesis-sourced result files for the dashboard. Every function reads a
real file under Code/stage2_output/ (or recomputes directly from the raw
probabilities saved there) and returns its data plus the path it came from --
the dashboard must never display a number that isn't traceable to one of these
reads.
"""

from __future__ import annotations

import csv
import json
from pathlib import Path

import numpy as np

from .inference import CODE_ROOT

STAGE2 = CODE_ROOT / "stage2_output"

ENSEMBLE_STEM = "ensemble_confusion_matrix_sensor2_merged23_10class"
SENSOR_COMPARISON_CSV = STAGE2 / "sensor_comparison_10class.csv"
CALIBRATION_JSON = STAGE2 / "calibration_sensor_2.json"
CALIBRATION_OPS_CSV = STAGE2 / "calibration_operating_points_sensor_2.csv"
CALIBRATION_PROBS_NPZ = STAGE2 / "calibration_probs_sensor_2.npz"

STATIC_PREFIX = "/api/stage2-output"  # where main.py mounts STAGE2 (under the /api router)


def _rel(path: Path) -> str:
    return str(path.relative_to(CODE_ROOT)).replace("\\", "/")


def _static_url(path: Path) -> str:
    return STATIC_PREFIX + "/" + path.name


def sensor_comparison() -> dict:
    """S1 vs S2 vs S3 on the ten shared classes. Source: sensor_comparison_10class.csv
    (regenerated by export_final_model.py's evaluation; matches chapters/08_sensors.tex)."""
    with open(SENSOR_COMPARISON_CSV, encoding="utf-8") as f:
        lines = [line for line in f.read().splitlines()]  # universal-newline text mode: \r\n -> \n already

    marker = lines.index("system comparison")
    per_class_lines = [ln for ln in lines[:marker] if ln.strip()]
    system_lines = [ln for ln in lines[marker + 1:] if ln.strip()]

    per_class = list(csv.DictReader(per_class_lines))
    system_rows = list(csv.DictReader(system_lines))

    return {
        "per_class": per_class,
        "system_comparison": system_rows,
        "source": _rel(SENSOR_COMPARISON_CSV),
        "source_url": _static_url(SENSOR_COMPARISON_CSV),
    }


def ensemble_confusion_matrix() -> dict:
    """The deployed Sensor-2 ensemble's own 10-class confusion matrix, generated by
    webapp/backend/scripts/make_ensemble_confusion_matrix.py (Stage 2/5 of this build)."""
    counts_path = STAGE2 / f"{ENSEMBLE_STEM}_counts.csv"
    pct_path = STAGE2 / f"{ENSEMBLE_STEM}_row_percent.csv"
    per_class_path = STAGE2 / f"{ENSEMBLE_STEM}_per_class_report.csv"
    png_path = STAGE2 / f"{ENSEMBLE_STEM}.png"

    with open(counts_path, newline="", encoding="utf-8") as f:
        rows = list(csv.reader(f))
    class_list = rows[0][1:]
    counts = [[int(v) for v in row[1:]] for row in rows[1:]]

    with open(pct_path, newline="", encoding="utf-8") as f:
        pct_rows = list(csv.reader(f))
    row_percent = [[float(v) for v in row[1:]] for row in pct_rows[1:]]

    with open(per_class_path, newline="", encoding="utf-8") as f:
        per_class = list(csv.DictReader(f))

    overall = next(r for r in per_class if r["fault_type"] == "OVERALL")
    per_class = [r for r in per_class if r["fault_type"] != "OVERALL"]
    total = sum(sum(row) for row in counts)
    correct = sum(counts[i][i] for i in range(len(class_list)))

    return {
        "classes": class_list,
        "counts": counts,
        "row_percent": row_percent,
        "per_class": per_class,
        "accuracy": correct / total if total else 0.0,
        "macro_f1": float(overall["f1"]),
        "n": total,
        "source_csv": _rel(counts_path),
        "source_csv_url": _static_url(counts_path),
        "source_per_class_csv": _rel(per_class_path),
        "source_per_class_csv_url": _static_url(per_class_path),
        "source_png": _rel(png_path),
        "source_png_url": _static_url(png_path),
        "generated_by": "webapp/backend/scripts/make_ensemble_confusion_matrix.py",
    }


def calibration() -> dict:
    """Calibration summary (ECE/MCE/Brier/NLL), reliability diagram bins and the
    coverage-vs-accuracy operating points for the Sensor-2 ensemble, uncalibrated
    (the version the field tool actually reports -- see chapters/09_calibration.tex,
    "The selected model therefore reports the uncalibrated ensemble confidence.")."""
    with open(CALIBRATION_JSON, encoding="utf-8") as f:
        cal = json.load(f)
    summary = cal["test_report"]["Ensemble"]["uncalibrated"]

    with open(CALIBRATION_OPS_CSV, newline="", encoding="utf-8") as f:
        operating_points = list(csv.DictReader(f))

    # Reliability bins are not pre-saved anywhere; recompute them the same way
    # the thesis does (prpd_calibration.metrics.reliability_bins, 15 equal-width
    # bins) directly from the saved test-split probabilities/labels, so the
    # diagram is traceable to calibration_probs_sensor_2.npz rather than retyped.
    from prpd_calibration.metrics import reliability_bins  # local import: needs CODE_ROOT on sys.path

    npz = np.load(CALIBRATION_PROBS_NPZ)
    probs = npz["test_Ensemble"]
    labels = npz["labels_test"]
    bins = reliability_bins(probs, labels, n_bins=15)
    bins = [b for b in bins if b["count"] > 0]

    return {
        "summary": summary,
        "reliability_bins": bins,
        "operating_points": operating_points,
        "source_json": _rel(CALIBRATION_JSON),
        "source_json_url": _static_url(CALIBRATION_JSON),
        "source_ops_csv": _rel(CALIBRATION_OPS_CSV),
        "source_ops_csv_url": _static_url(CALIBRATION_OPS_CSV),
        "source_probs_npz": _rel(CALIBRATION_PROBS_NPZ),
        "source_probs_npz_url": _static_url(CALIBRATION_PROBS_NPZ),
        "reliability_method": "prpd_calibration.metrics.reliability_bins (same function as the thesis), n_bins=15",
    }
